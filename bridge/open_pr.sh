#!/usr/bin/env bash
# Create a branch from the current (fixed) working tree, push it to GitHub, and
# open a pull request against main via the GitHub REST API.
#
# Requires env: GITHUB_OWNER, GITHUB_REPO, GITHUB_PAT
set -euo pipefail

BR="devops-agent/remediate-claims-422-$(date +%Y%m%d-%H%M%S)"
git config user.email "devops-agent-bot@users.noreply.github.com"
git config user.name "aws-devops-agent-bot"
git checkout -b "$BR"
git add app/validation.py app/query.sql 2>/dev/null || git add -A

git commit -m "fix(claims-api): restore valid claim validation (auto-remediation)" \
           -m "Automated fix generated by Kiro CLI from the AWS DevOps Agent mitigation plan for the claims-api HTTP 422 incident. Restores the reference-length boundary and the claim_type allowlist so valid POST /claims requests are accepted. Human review required before merge."

git push "https://${GITHUB_OWNER}:${GITHUB_PAT}@github.com/${GITHUB_OWNER}/${GITHUB_REPO}.git" "HEAD:${BR}" 2>&1 | sed "s/${GITHUB_PAT}/***REDACTED***/g"

PR_TITLE="fix(claims-api): auto-remediation for HTTP 422 incident"
PR_BODY="This pull request was generated automatically by Kiro CLI from the AWS DevOps Agent mitigation plan. It restores valid claim validation in the claims-api service (reference-length boundary and claim_type allowlist) so that valid POST /claims requests are no longer rejected with HTTP 422. Human review required before merge."

# Build the JSON body safely with python, then POST it.
python3 - "$BR" "$PR_TITLE" "$PR_BODY" > /tmp/pr_payload.json <<'PY'
import json, sys
branch, title, body = sys.argv[1], sys.argv[2], sys.argv[3]
print(json.dumps({"title": title, "head": branch, "base": "main", "body": body}))
PY

RESP="$(curl -sS -X POST \
  -H "Authorization: Bearer ${GITHUB_PAT}" \
  -H "Accept: application/vnd.github+json" \
  "https://api.github.com/repos/${GITHUB_OWNER}/${GITHUB_REPO}/pulls" \
  -d @/tmp/pr_payload.json)"

echo "$RESP" | sed "s/${GITHUB_PAT}/***REDACTED***/g" | python3 -c "import json,sys; d=json.load(sys.stdin); print('PR:', d.get('html_url') or ('ERROR: ' + str(d.get('message'))))"
